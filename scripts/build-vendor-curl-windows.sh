#!/usr/bin/env bash
# scripts/build-vendor-curl-windows.sh
#
# Cross-builds a REAL, statically linkable libcurl for Windows
# (`x86_64-windows-gnu`) and installs it at
# `vendor/curl/windows-amd64/{lib/libcurl.a,include/curl/*.h}` — the path
# `build.zig` already looks in before it falls back to the no-op stub.
#
# Why Windows is built with Schannel and nothing else:
#   - Schannel IS Windows' TLS stack (the system certificate store), so the
#     archive needs no OpenSSL: no libssl.a/libcrypto.a, no `-lssl`, no
#     `-lcrypto`, no second TLS version to keep patched.
#   - Every other optional dependency (zlib, brotli, zstd, libpsl, libidn2,
#     libssh2, nghttp2, c-ares) is turned OFF, so the only symbols the archive
#     leaves undefined are Win32 system ones that Zig's bundled mingw-w64
#     already provides: ws2_32 crypt32 secur32 bcrypt advapi32 user32
#     iphlpapi wldap32 normaliz.
#   - That is what makes `zig build` on a bare Windows dev box (no vcpkg, no
#     MSYS2, no Visual Studio) produce a client that can actually reach the
#     network — which is the whole point of this file.
#
# Why `zig cc` (and not a real mingw-w64 or MSVC toolchain):
#   Kurir/kabelweb link with Zig's own `x86_64-windows-gnu` target, whose
#   runtime is Zig's bundled mingw-w64. Compiling curl with `zig cc -target
#   x86_64-windows-gnu` produces objects for exactly that toolchain — no ABI
#   or CRT drift — and needs nothing installed on the machine that runs this
#   script beyond Zig itself.
#
# Requires (host): bash, curl, tar, zig 0.16+, cmake 3.20+.
# Verified on macOS arm64 and on ubuntu-24.04 (see .github/workflows/ci.yml,
# the `vendor-curl-windows` job).
#
# Layout written:
#   vendor/curl/windows-amd64/include/curl/*.h
#   vendor/curl/windows-amd64/lib/libcurl.a
#
# Usage:
#   scripts/build-vendor-curl-windows.sh            # build into ./vendor
#   CURL_VERSION=8.14.1 scripts/build-vendor-curl-windows.sh
#   OUT_DIR=/tmp/curlwin scripts/build-vendor-curl-windows.sh
#
# The output is committed to the repository on purpose: kabelweb is consumed
# by URL + hash, so a build archive that is not in git does not exist for
# consumers. Re-run this script after changing CURL_VERSION, and commit the
# new archive in the same commit as the version bump.
set -euo pipefail

CURL_VERSION="${CURL_VERSION:-8.10.1}"
CURL_URL="https://curl.se/download/curl-${CURL_VERSION}.tar.gz"

# The Zig target the archive is compiled for. MUST match the target Zig
# resolves for a Windows consumer (kurirw passes `-Dtarget=x86_64-windows-gnu`
# only implicitly — that is Zig's default Windows target).
ZIG_TARGET="x86_64-windows-gnu"

# Repo root = parent of scripts/.
PKG_DIR="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="${OUT_DIR:-${PKG_DIR}/vendor/curl/windows-amd64}"

# Source + build tree. Cached between runs (curl source is 3 MB; a rebuild is
# ~90 s, a re-download is worse).
WORK_DIR="${WORK_DIR:-${TMPDIR:-/tmp}/pabrik/curl-windows-build}"
SRC_DIR="${WORK_DIR}/curl-${CURL_VERSION}"
BUILD_DIR="${WORK_DIR}/build"
WRAP_DIR="${WORK_DIR}/wrap"

ZIG="${ZIG:-zig}"
CMAKE="${CMAKE:-cmake}"

need() { command -v "$1" >/dev/null 2>&1 || { echo "error: '$1' not found in PATH" >&2; exit 1; }; }
need curl
need tar
need "$ZIG"
need "$CMAKE"

mkdir -p "$WORK_DIR"

echo "=== zig $(  "$ZIG" version ) — target ${ZIG_TARGET} ==="
echo "=== curl ${CURL_VERSION} ==="
echo "=== output: ${OUT_DIR} ==="

# ── 1. Source ────────────────────────────────────────────────────────────
if [ ! -d "$SRC_DIR" ]; then
    tarball="${WORK_DIR}/curl-${CURL_VERSION}.tar.gz"
    if [ ! -f "$tarball" ]; then
        echo "=== downloading ${CURL_URL} ==="
        curl -fsSL --retry 3 -o "$tarball.part" "$CURL_URL"
        mv "$tarball.part" "$tarball"
    fi
    echo "=== extracting ==="
    tar -xzf "$tarball" -C "$WORK_DIR"
fi
test -f "${SRC_DIR}/CMakeLists.txt"

# ── 2. zig cc / zig ar wrappers for CMake ────────────────────────────────
#
# CMake takes a *path* for each tool, never "program + fixed arguments", so
# `zig cc -target …` has to be wrapped in a tiny script.
mkdir -p "$WRAP_DIR"
make_wrapper() {
    # make_wrapper <path> <zig subcommand...>
    local path="$1"; shift
    {
        echo '#!/bin/sh'
        printf 'exec "%s" %s "$@"\n' "$ZIG" "$*"
    } > "$path"
    chmod +x "$path"
}
make_wrapper "${WRAP_DIR}/cc"       cc -target "$ZIG_TARGET"
make_wrapper "${WRAP_DIR}/cxx"      c++ -target "$ZIG_TARGET"
make_wrapper "${WRAP_DIR}/ar"       ar
make_wrapper "${WRAP_DIR}/ranlib"   ranlib
# Only used if a .rc resource ever shows up in the curl build; harmless.
make_wrapper "${WRAP_DIR}/windres"  cc -target "$ZIG_TARGET" -c -x c

TOOLCHAIN="${WORK_DIR}/windows-gnu-toolchain.cmake"
cat > "$TOOLCHAIN" <<EOF
# Generated by scripts/build-vendor-curl-windows.sh — do not edit.
set(CMAKE_SYSTEM_NAME Windows)
set(CMAKE_SYSTEM_PROCESSOR x86_64)
set(CMAKE_C_COMPILER   "${WRAP_DIR}/cc")
set(CMAKE_CXX_COMPILER "${WRAP_DIR}/cxx")
set(CMAKE_AR           "${WRAP_DIR}/ar")
set(CMAKE_RANLIB       "${WRAP_DIR}/ranlib")
set(CMAKE_RC_COMPILER  "${WRAP_DIR}/windres")
# The compiler is known-good, and probing a Windows link on a POSIX host is
# the one thing that can wedge a CMake configure; skip the probe.
set(CMAKE_C_COMPILER_WORKS 1)
set(CMAKE_CXX_COMPILER_WORKS 1)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
EOF

# ── 3. Configure ─────────────────────────────────────────────────────────
#
# Every `-D…=OFF` below is deliberate: each one either removes a library we
# would then have to cross-build as well, or removes a feature Windows users of
# an HTTP client never touch. Anything left ON must resolve against Win32
# system libraries alone.
rm -rf "$BUILD_DIR"
"$CMAKE" -S "$SRC_DIR" -B "$BUILD_DIR" \
    -DCMAKE_TOOLCHAIN_FILE="$TOOLCHAIN" \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX="$BUILD_DIR/stage" \
    -DBUILD_SHARED_LIBS=OFF \
    -DBUILD_STATIC_LIBS=ON \
    -DBUILD_CURL_EXE=OFF \
    -DBUILD_EXAMPLES=OFF \
    -DBUILD_TESTING=OFF \
    -DPICKY_COMPILER=OFF \
    -DCURL_USE_SCHANNEL=ON \
    -DCURL_USE_OPENSSL=OFF \
    -DCURL_USE_MBEDTLS=OFF \
    -DCURL_USE_WOLFSSL=OFF \
    -DCURL_USE_BEARSSL=OFF \
    -DCURL_USE_GNUTLS=OFF \
    -DCURL_ZLIB=OFF \
    -DCURL_BROTLI=OFF \
    -DCURL_ZSTD=OFF \
    -DCURL_USE_LIBPSL=OFF \
    -DCURL_USE_LIBSSH2=OFF \
    -DCURL_USE_LIBSSH=OFF \
    -DCURL_USE_GSSAPI=OFF \
    -DUSE_NGHTTP2=OFF \
    -DUSE_NGTCP2=OFF \
    -DUSE_QUICHE=OFF \
    -DUSE_MSH3=OFF \
    -DENABLE_ARES=OFF \
    -DUSE_LIBIDN2=OFF \
    -DCURL_DISABLE_LDAP=ON \
    -DCURL_DISABLE_LDAPS=ON \
    -DCURL_DISABLE_SRP=ON \
    -DCURL_DISABLE_SMB=ON \
    -DCURL_DISABLE_GOPHER=ON \
    -DCURL_DISABLE_DICT=ON \
    -DCURL_DISABLE_TELNET=ON \
    -DCURL_DISABLE_TFTP=ON \
    -DCURL_DISABLE_IMAP=ON \
    -DCURL_DISABLE_POP3=ON \
    -DCURL_DISABLE_SMTP=ON \
    -DCURL_DISABLE_RTSP=ON \
    -DCURL_DISABLE_MQTT=ON \
    -DCURL_DISABLE_WEBSOCKETS=ON \
    -DCURL_ENABLE_SSL=ON \
    2>&1 | tail -25

# The configure has to have picked Schannel; a silent OpenSSL fallback would
# produce an archive with undefined SSL_* symbols and a confusing link error
# much later, on somebody else's machine.
if ! grep -q 'CMAKE_USE_SCHANNEL:BOOL=ON\|CURL_USE_SCHANNEL' "$BUILD_DIR/CMakeCache.txt"; then
    echo "error: CMake did not select Schannel — see ${BUILD_DIR}/CMakeCache.txt" >&2
    exit 1
fi

# ── 4. Build + install into a staging prefix ─────────────────────────────
"$CMAKE" --build "$BUILD_DIR" --parallel "$( (nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 4) )" 2>&1 | tail -15
"$CMAKE" --install "$BUILD_DIR" 2>&1 | tail -5

STAGE="$BUILD_DIR/stage"
test -f "${STAGE}/lib/libcurl.a" || { echo "error: no libcurl.a in ${STAGE}/lib" >&2; exit 1; }

# ── 5. Copy exactly what the Zig build consumes ──────────────────────────
#
# Only the archive and the public headers: `curl-config`, the CMake package
# files and the pkg-config file describe a POSIX install and would just be
# dead weight in the repository.
rm -rf "$OUT_DIR"
mkdir -p "${OUT_DIR}/lib" "${OUT_DIR}/include"
cp "${STAGE}/lib/libcurl.a" "${OUT_DIR}/lib/libcurl.a"
cp -R "${STAGE}/include/curl" "${OUT_DIR}/include/curl"

# ── 6. Verify by LINKING, not by inspecting ──────────────────────────────
#
# The obvious check — `nm libcurl.a | grep curl_easy_perform` — cannot be done
# here: the host's `nm` reads ELF/Mach-O, not COFF, so it either errors or
# prints nothing and a "no symbols" warning on a perfectly good archive. The
# check that actually means something is the one the consumer will do: link a
# program against the archive for the SAME target, with the SAME Win32 library
# list `build.zig` uses. If that links, a consumer links.
echo "=== verify: link a real probe for ${ZIG_TARGET} ==="
PROBE_DIR="${WORK_DIR}/probe"
rm -rf "$PROBE_DIR"
mkdir -p "$PROBE_DIR"
cat > "${PROBE_DIR}/probe.c" <<'EOF'
#include <curl/curl.h>
int main(void) {
    CURL *c = curl_easy_init();
    if (!c) return 1;
    curl_easy_setopt(c, CURLOPT_URL, "https://example.com/");
    CURLcode rc = curl_easy_perform(c);
    curl_easy_cleanup(c);
    return (int)rc == 0 ? 0 : 2;
}
EOF
# The Win32 library list MUST stay in sync with build.zig's vendored branch.
"$ZIG" cc -target "$ZIG_TARGET" -DCURL_STATICLIB \
    -I"${OUT_DIR}/include" \
    "${PROBE_DIR}/probe.c" "${OUT_DIR}/lib/libcurl.a" \
    -lws2_32 -lcrypt32 -lsecur32 -lbcrypt -ladvapi32 -luser32 \
    -liphlpapi -lwldap32 -lnormaliz \
    -o "${PROBE_DIR}/probe.exe"
test -f "${PROBE_DIR}/probe.exe" || { echo "error: the probe did not link" >&2; exit 1; }

echo "=== done ==="
du -h "${OUT_DIR}/lib/libcurl.a" | awk '{print "  archive: "$1}'
du -h "${PROBE_DIR}/probe.exe" | awk '{print "  probe.exe (curl linked in): "$1}'
echo "  headers: $(ls "${OUT_DIR}/include/curl" | wc -l | tr -d ' ')"

